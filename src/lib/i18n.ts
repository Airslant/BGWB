import { BOARD_STATUSES, SUPPORTED_LOCALES, type BoardStatus, type GameSnapshot, type Locale } from "./types";
import { decodeHtmlEntities } from "./html-entities";

export const DEFAULT_LOCALE: Locale = "en";

export function normalizeLocale(value: unknown): Locale {
  if (value === "zh-CN" || value === "zh" || value === "zh-Hans" || value === "zh_CN") {
    return "zh-CN";
  }

  if (value === "en" || value === "en-US" || value === "en-GB") {
    return "en";
  }

  if (typeof value === "string" && value.toLowerCase().startsWith("zh")) {
    return "zh-CN";
  }

  return DEFAULT_LOCALE;
}

export function isSupportedLocale(value: unknown): value is Locale {
  return SUPPORTED_LOCALES.includes(value as Locale);
}

export function getGameDisplayName(game: Pick<GameSnapshot, "name" | "displayName" | "localizedNames">, locale: Locale) {
  return decodeHtmlEntities(game.displayName || game.localizedNames?.[locale] || game.localizedNames?.en || game.name);
}

export function getDefaultBoardTitle(locale: Locale) {
  return locale === "zh-CN" ? "我的桌游白板" : "My Board Game Whiteboard";
}

export function splitAliases(value: string) {
  return Array.from(
    new Set(
      value
        .split(/[\n,，]/)
        .map((alias) => alias.trim())
        .filter(Boolean)
    )
  ).slice(0, 24);
}

export function joinAliases(value: string[] | undefined) {
  return (value ?? []).join("\n");
}

